# y 0xB000 eligen lo que se ve en 0x6000, 0x8000 y 0xA000.
REGISTROS_MAPPER = {0x7000: "0x6000", 0x9000: "0x8000", 0xB000: "0xA000"}


# Que banco se ve en cada ventana al empezar una rutina del banco b. El juego
# corre con 1-2-3 (p00:4108) y cambia solo 0xA000 (p00:4133-414E) o 0x8000 y
# 0xA000 (p00:4157); el banco 4 es el sonido, que se llama con 4-5-6
# (p00:4AE4, p00:403B). El banco 0 (0x4000) no tiene reparto fijo.
def trio(b):
    if b == 0:
        return {}
    if b == 4:
        return {0x6000: 4, 0x8000: 5, 0xA000: 6}
    return {0x6000: 1, 0x8000: 2, 0xA000: b if b in (3, 10, 11) else 3}


